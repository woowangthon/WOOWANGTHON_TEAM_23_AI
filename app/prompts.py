QUESTION_PROMPT = """다음은 사용자가 공부하려는 학습 자료의 일부임. 이 내용만 근거로 문제를 만들 것.
OX 문제 3개와 단답형 문제 2개를 JSON으로만 출력함. 서로 다른 내용을 묻고, 같은 문장이나 같은 개념을 반복해 묻지 않음.

규칙
- OX 문제는 true에 자료와 맞는 서술문, false에 같은 문장에서 사실 하나(숫자, 이름, 용어, 관계 등)만 바꿔 자료와 어긋나게 만든 서술문을 씀. 둘 다 물음표를 쓰지 않음
- false는 자료를 읽으면 틀렸다고 확실히 가릴 수 있어야 함. 바꾼 값이 자료의 값과 함께 참일 수 없어야 함. 수식어를 빼거나 비슷한 말로 바꿔 여전히 참으로 읽히는 문장, 자료로 판단할 수 없는 문장은 쓰지 않음
- 단답형 문제는 "~는 무엇인가?", "~를 무엇이라 하는가?"처럼 의문문으로 쓰고 물음표로 끝냄. "~의 약자", "~하는 기호" 같은 명사구로 끝내지 않음
- 문제 문장에 정답을 쓰지 않음
- "자료에서", "본문에 언급된" 같이 자료를 가리키는 표현을 쓰지 않음. 문제만 읽고 풀 수 있어야 함
- 단답형 정답은 명사 하나이고 공백을 빼고 10자 이내임. 문장이나 설명으로 답하는 문제는 내지 않음
- accepted에는 정답과 같은 대상을 가리키는 다른 이름을 모두 적음. 정식 명칭, 줄임말, 다른 표기, 영어 이름 등. 예: 정답이 헌법이면 대한민국헌법, 한국 헌법
- evidence에는 자료의 한 문장을 글자 그대로 복사해 넣음

형식: {"questions":[{"type":"ox","true":"","false":"","evidence":""},{"type":"short","question":"","answer":"","accepted":[""],"evidence":""}, ...]} (questions 배열에 OX 3개와 단답형 2개)

자료:
"""

AVOID_BLOCK = """이미 낸 문제임. 이 문제들과 같은 내용이나 같은 개념을 묻지 않고, 자료의 다른 내용으로 새 문제를 만들 것.
{items}

"""


def question_prompt(avoid: list[str]) -> str:
    """이미 낸 문제가 있으면 자료 앞에 붙여 같은 내용을 다시 묻지 않게 함"""
    if not avoid:
        return QUESTION_PROMPT
    block = AVOID_BLOCK.format(items="\n".join(f"- {q}" for q in avoid))
    return QUESTION_PROMPT.replace("자료:\n", block + "자료:\n")


